"""A small synthetic multi-region network, for watching the engine run.

PROVENANCE: this network is **synthetic**. Every neuron and every synapse it
produces is generated by the code in this file from a fixed seed. Nothing here
is measured, fitted to measured data, or anatomically derived. The region names
(``sensory``, ``assoc_a``, ``assoc_b``, ``threat``, ``inhib``) are labels for
blocks of the generated graph; they are not claims about brain anatomy.

The generator, its parameters and its seed are recorded in
:attr:`DemoNetwork.provenance` so a consumer can filter on them, per ADR-0004.

Why this exists
---------------
The observability layer (ADR-0007) needs a network that is small enough to
stream at interactive rates, structured enough that "per-region activity" means
something, and honest about being made up. This is that network. It is a
*fixture*, not a model of a brain region.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

import numpy as np

from ..connectome.sparse import SparseConnectome
from ..neurons.base import LIFNeuron
from ..simulation.backend import LIFState

#: Generator identity, recorded in provenance.
GENERATOR = "mem20_brainz.scenarios.demo_network.build_demo_network"
GENERATOR_VERSION = "1"

#: Default population size per region. Chosen so the whole network streams
#: smoothly in a browser canvas while still having distinguishable regions.
DEFAULT_REGION_SIZES: dict[str, int] = {
    "sensory": 120,
    "assoc_a": 160,
    "assoc_b": 160,
    "threat": 80,
    "inhib": 60,
}

#: Regions that contain excitatory projection neurons.
EXCITATORY_REGIONS = ("sensory", "assoc_a", "assoc_b", "threat")

#: The region the ``fear_like`` readout restricts its synchrony term to.
#: A configuration choice, not a biological identification.
DEFAULT_THREAT_REGION = "threat"


@dataclass(frozen=True)
class RegionSpec:
    """A contiguous block of neuron indices with a display layout."""

    name: str
    start: int
    stop: int
    kind: str  # "excitatory" | "inhibitory"
    #: Centre of the region's disc in layout space, in [0, 1] x [0, 1].
    center: tuple[float, float]

    @property
    def count(self) -> int:
        return self.stop - self.start

    @property
    def indices(self) -> np.ndarray:
        return np.arange(self.start, self.stop, dtype=np.int32)


@dataclass
class DemoNetwork:
    """A built network: state, wiring, layout and provenance."""

    state: LIFState
    connectome: SparseConnectome
    regions: list[RegionSpec]
    positions: np.ndarray  # (n_neurons, 2) in [0, 1]^2, for display only
    baseline_rate_hz: float
    threat_region: str
    provenance: dict[str, Any] = field(default_factory=dict)

    @property
    def n_neurons(self) -> int:
        return self.state.n_neurons

    @property
    def n_synapses(self) -> int:
        return self.connectome.n_synapses

    def region_of(self, neuron_index: int) -> str:
        for region in self.regions:
            if region.start <= neuron_index < region.stop:
                return region.name
        raise IndexError(f"neuron index {neuron_index} is outside every region")

    def region_indices(self, name: str) -> np.ndarray:
        for region in self.regions:
            if region.name == name:
                return region.indices
        raise KeyError(f"unknown region {name!r}")

    def region_names(self) -> list[str]:
        return [r.name for r in self.regions]


def _region_centers(names: list[str]) -> dict[str, tuple[float, float]]:
    """Place regions on a ring, deterministically, for display only."""
    n = len(names)
    centers: dict[str, tuple[float, float]] = {}
    for i, name in enumerate(names):
        angle = 2.0 * np.pi * i / n - np.pi / 2.0
        centers[name] = (0.5 + 0.34 * float(np.cos(angle)), 0.5 + 0.34 * float(np.sin(angle)))
    return centers


def _layout(regions: list[RegionSpec], rng: np.random.Generator) -> np.ndarray:
    """Scatter each region's neurons in a disc around its centre.

    Display coordinates only. They are not soma positions in any reference
    space and must not be read as anatomy (see ``docs/data-model.md``).
    """
    positions = np.zeros((regions[-1].stop, 2), dtype=np.float64)
    for region in regions:
        n = region.count
        # Deterministic sunflower packing plus a little jitter: even coverage,
        # no clumping, and stable across runs for a given seed.
        idx = np.arange(n, dtype=np.float64)
        golden = np.pi * (3.0 - np.sqrt(5.0))
        radius = 0.115 * np.sqrt((idx + 0.5) / max(n, 1))
        theta = idx * golden
        jitter = rng.normal(0.0, 0.004, size=(n, 2))
        positions[region.start : region.stop, 0] = region.center[0] + radius * np.cos(theta)
        positions[region.start : region.stop, 1] = region.center[1] + radius * np.sin(theta)
        positions[region.start : region.stop] += jitter
    return np.clip(positions, 0.0, 1.0)


def _connect(
    src: np.ndarray,
    dst: np.ndarray,
    p: float,
    weight: float,
    delay_range: tuple[float, float],
    rng: np.random.Generator,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Sample a random bipartite edge set with fixed probability ``p``.

    Edges are sampled directly rather than by masking a dense ``len(src) x
    len(dst)`` matrix, because ADR-0001 forbids materialising a dense
    neuron-by-neuron structure anywhere in the project, fixtures included.
    """
    if src.size == 0 or dst.size == 0 or p <= 0.0:
        empty_i = np.empty(0, dtype=np.int32)
        empty_f = np.empty(0, dtype=np.float32)
        return empty_i, empty_i, empty_f, empty_f

    n_pairs = int(src.size * dst.size)
    n_edges = int(rng.binomial(n_pairs, p))
    if n_edges == 0:
        empty_i = np.empty(0, dtype=np.int32)
        empty_f = np.empty(0, dtype=np.float32)
        return empty_i, empty_i, empty_f, empty_f

    flat = rng.choice(n_pairs, size=n_edges, replace=False)
    pre = src[flat // dst.size].astype(np.int32)
    post = dst[flat % dst.size].astype(np.int32)
    w = np.full(n_edges, weight, dtype=np.float32)
    # Lognormal spread so the network is not perfectly homogeneous.
    w *= rng.lognormal(mean=0.0, sigma=0.18, size=n_edges).astype(np.float32)
    delay = rng.uniform(delay_range[0], delay_range[1], size=n_edges).astype(np.float32)
    return pre, post, w, delay


def build_demo_network(
    region_sizes: dict[str, int] | None = None,
    seed: int = 20261101,
    baseline_rate_hz: float = 5.0,
    threat_region: str = DEFAULT_THREAT_REGION,
) -> DemoNetwork:
    """Build the synthetic demo network.

    Parameters
    ----------
    region_sizes:
        Override the per-region neuron counts. Keys must be a subset of
        :data:`DEFAULT_REGION_SIZES`.
    seed:
        Seed for every random draw. Recorded in provenance; the same seed
        always produces the same network.
    baseline_rate_hz:
        The reference rate the ``arousal`` readout divides by. A stated
        parameter, not a measured constant.
    threat_region:
        Which region the ``fear_like`` readout uses for its synchrony term.
    """
    sizes = dict(DEFAULT_REGION_SIZES)
    if region_sizes:
        unknown = set(region_sizes) - set(sizes)
        if unknown:
            raise KeyError(f"unknown region(s): {sorted(unknown)}")
        sizes.update(region_sizes)
    if threat_region not in sizes:
        raise KeyError(f"threat_region {threat_region!r} is not a region")

    rng = np.random.default_rng(seed)

    names = list(sizes)
    centers = _region_centers(names)

    regions: list[RegionSpec] = []
    cursor = 0
    for name in names:
        count = int(sizes[name])
        kind = "inhibitory" if name == "inhib" else "excitatory"
        regions.append(
            RegionSpec(
                name=name,
                start=cursor,
                stop=cursor + count,
                kind=kind,
                center=centers[name],
            )
        )
        cursor += count
    n_neurons = cursor

    # --- neuron parameters -------------------------------------------------
    # Textbook LIF defaults with mild per-neuron heterogeneity, so the
    # population is not degenerate. These are placeholders, not fitted values.
    neurons: list[LIFNeuron] = []
    for i in range(n_neurons):
        neurons.append(
            LIFNeuron(
                id=i,
                v_rest=-70.0,
                v_reset=-75.0,
                v_threshold=float(-50.0 + rng.normal(0.0, 1.2)),
                tau_m=float(20.0 + rng.normal(0.0, 1.5)),
                r_m=10.0,
                refractory_ms=2.0,
                v=-70.0,
            )
        )
    state = LIFState.from_neurons(neurons)

    # --- wiring ------------------------------------------------------------
    by_name = {r.name: r for r in regions}
    inh = by_name["inhib"].indices if "inhib" in by_name else np.empty(0, np.int32)

    parts: list[tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]] = []

    # Recurrent excitation inside each excitatory region.
    for name in EXCITATORY_REGIONS:
        if name not in by_name:
            continue
        idx = by_name[name].indices
        p = 0.16 if name == "threat" else 0.12
        parts.append(_connect(idx, idx, p, 0.30, (1.0, 3.0), rng))

    # Feedforward chain: sensory -> assoc_a -> assoc_b, plus feedback. Every
    # excitatory region also receives a weak direct projection from sensory, so
    # no region is structurally silent: a region that never fires would make the
    # cross-region dispersion readout meaningless.
    chain = [
        ("sensory", "assoc_a", 0.10, 0.30),
        ("assoc_a", "assoc_b", 0.10, 0.30),
        ("assoc_b", "assoc_a", 0.06, 0.22),
        ("assoc_a", "threat", 0.08, 0.30),
        ("sensory", "assoc_b", 0.04, 0.20),
        ("sensory", "threat", 0.05, 0.24),
        ("assoc_b", "sensory", 0.05, 0.22),
    ]
    for src_name, dst_name, p, w in chain:
        if src_name in by_name and dst_name in by_name:
            parts.append(
                _connect(
                    by_name[src_name].indices,
                    by_name[dst_name].indices,
                    p,
                    w,
                    (1.0, 4.0),
                    rng,
                )
            )

    # Feedforward inhibition: every excitatory region drives the inhibitory pool.
    for name in EXCITATORY_REGIONS:
        if name in by_name and inh.size:
            parts.append(_connect(by_name[name].indices, inh, 0.18, 0.30, (1.0, 3.0), rng))

    # Feedback inhibition: the pool inhibits every excitatory region. The weight
    # is deliberately comparable to the excitatory weights above: with a much
    # weaker pool the network is purely excitatory and the valence readout sits
    # pinned at +1, which would make the gauge useless.
    if inh.size:
        for name in EXCITATORY_REGIONS:
            if name in by_name:
                parts.append(_connect(inh, by_name[name].indices, 0.22, -0.75, (1.0, 3.0), rng))

    pre = np.concatenate([p[0] for p in parts]) if parts else np.empty(0, np.int32)
    post = np.concatenate([p[1] for p in parts]) if parts else np.empty(0, np.int32)
    weight = np.concatenate([p[2] for p in parts]) if parts else np.empty(0, np.float32)
    delay = np.concatenate([p[3] for p in parts]) if parts else np.empty(0, np.float32)

    connectome = SparseConnectome.from_arrays(
        n_neurons=n_neurons, pre=pre, post=post, weight=weight, delay_ms=delay
    )

    positions = _layout(regions, rng)

    provenance: dict[str, Any] = {
        "kind": "synthetic",
        "generator": GENERATOR,
        "generator_version": GENERATOR_VERSION,
        "seed": seed,
        "fitted_to": None,
        "fitted_to_note": (
            "Not fitted to any measured dataset. Edge probabilities and weights are "
            "hand-chosen to produce visible, non-degenerate dynamics."
        ),
        "region_sizes": {r.name: r.count for r in regions},
        "n_neurons": n_neurons,
        "n_synapses": int(connectome.n_synapses),
        "neuron_model_tier": "tier0_point_lif",
        "parameters_are_placeholders": True,
    }

    return DemoNetwork(
        state=state,
        connectome=connectome,
        regions=regions,
        positions=positions,
        baseline_rate_hz=baseline_rate_hz,
        threat_region=threat_region,
        provenance=provenance,
    )
